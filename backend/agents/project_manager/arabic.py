"""Arabic number agreement: 1 حقل · 2 حقلان · 3–10 حقول · 11+ حقلاً."""

from __future__ import annotations

# word: (one, two, few 3-10, many 11+)
WORDS = {
    "field": ("حقل واحد", "حقلان", "حقول", "حقلاً"),
    "requirement": ("متطلب واحد", "متطلبان", "متطلبات", "متطلباً"),
    "story": ("قصة مستخدم واحدة", "قصتا مستخدم", "قصص مستخدم", "قصة مستخدم"),
    "screen": ("شاشة واحدة", "شاشتان", "شاشات", "شاشة"),
    "second": ("ثانية واحدة", "ثانيتان", "ثوانٍ", "ثانية"),
    "repair": ("إصلاح واحد", "إصلاحين", "إصلاحات", "إصلاحاً"),
    "criterion": ("معيار قبول واحد", "معيارا قبول", "معايير قبول", "معيار قبول"),
    "assumption": ("افتراض واحد", "افتراضين", "افتراضات", "افتراضاً"),
    "check": ("فحص واحد", "فحصان", "فحوصات", "فحصاً"),
    "entity": ("كيان واحد", "كيانان", "كيانات", "كياناً"),
}


def count(n: int, word: str) -> str:
    one, two, few, many = WORDS[word]
    n = int(n)
    if n == 1:
        return one
    if n == 2:
        return two
    if 3 <= n % 100 <= 10:
        return f"{n} {few}"
    return f"{n} {many}"
