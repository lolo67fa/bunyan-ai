_PLAN_OUTPUTS = [
    ("st_analysis", ["requirements.json"]),
    ("st_design", ["architecture.json"]),
    ("st_code", ["index.html", "style.css", "app.js"]),
    ("st_test", ["test_report.json"]),
    ("st_docs", [PLAN_FILE, RISKS_FILE]),
]


def build_documents(
    requirements: Dict[str, Any],
    architecture: Dict[str, Any],
    qa_report: Optional[Dict[str, Any]] = None,
    run: Optional[Dict[str, Any]] = None,
    files: Optional[Dict[str, int]] = None,
    now: Optional[datetime] = None,
) -> Dict[str, str]:
    """Return ``{"project_plan.md": text, "risks.md": text}``. Raises ProjectManagerError."""
    _check_inputs(requirements, architecture)
    run = run or {}
    files = files or {}
    now = now or datetime.now(timezone.utc)
    language = requirements.get("language") if requirements.get("language") in _TEXT else "en"
    t = _TEXT[language]
    qa = _qa_view(qa_report, run)
    return {
        PLAN_FILE: _plan(requirements, architecture, qa_report, run, files, now, t, qa),
        RISKS_FILE: _risks(requirements, architecture, qa_report, run, now, t, qa),
    }


def write_documents(
    requirements: Dict[str, Any],
    architecture: Dict[str, Any],
    output_dir: Any,
    qa_report: Optional[Dict[str, Any]] = None,
    run: Optional[Dict[str, Any]] = None,
    files: Optional[Dict[str, int]] = None,
    now: Optional[datetime] = None,
) -> Dict[str, str]:
    """Write both documents into ``output_dir`` and return ``{name: path}``."""
    documents = build_documents(requirements, architecture, qa_report, run, files, now)
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    written = {}
    for name, text in documents.items():
        (out / name).write_text(text, encoding="utf-8")
        written[name] = str(out / name)
    return written


# ---------- inputs ----------


def _check_inputs(requirements: Any, architecture: Any) -> None:
    if not isinstance(requirements, dict) or not isinstance(requirements.get("app"), dict):
        raise ProjectManagerError("Requirements are missing or have no 'app' section")
    if not requirements["app"].get("name"):
        raise ProjectManagerError("Requirements have no application name")
    if not isinstance(architecture, dict) or not isinstance(architecture.get("entity"), dict):
        raise ProjectManagerError("Architecture is missing or has no 'entity' section")


def _qa_view(report: Optional[Dict[str, Any]], run: Dict[str, Any]) -> Dict[str, Any]:
    """What is known about testing. The report is the source; the run state only says why there is none."""
    status = (run.get("qa") or {}).get("status")
    if not isinstance(report, dict) or not isinstance(report.get("summary"), dict):
        return {"status": "blocked" if status == "blocked" else "not_run", "summary": None, "failed": [], "skipped": []}
    summary = report["summary"]
    checks = report.get("checks") or []
    failed = [c for c in checks if c.get("status") == "failed"]
    skipped = [c for c in checks if c.get("status") == "skipped"]
    if (report.get("run") or {}).get("blocked_reason") or summary.get("not_run", 0) > 0:
        outcome = "blocked"
    elif summary.get("failed", 0) > 0:
        outcome = "failed"
    else:
        outcome = "passed"
    return {"status": outcome, "summary": summary, "failed": failed, "skipped": skipped}


# ---------- project_plan.md ----------


def _plan(req, arch, report, run, files, now, t, qa) -> str:
    app = req["app"]
    entity = arch["entity"]
    functional = req.get("functional_requirements") or []
    must = sum(1 for r in functional if r.get("priority") == "must")
    metrics = run.get("metrics") or {}
    lines: List[str] = [f"# {t['plan_title'].format(name=app['name'])}", "", f"> {t['generated'].format(when=_stamp(now))}", ""]

    lines += [f"## {t['summary']}", ""]
    lines += [
        f"- {t['application']}: {app['name']}",
        f"- {t['description']}: {app.get('description') or t['not_available']}",
        f"- {t['language']}: {req.get('language') or t['not_available']}",
        f"- {t['entity']}: {entity.get('label') or entity.get('name')} (`{entity.get('name')}`)",
        f"- {t['fields']}: {len(entity.get('fields') or [])}",
        f"- {t['requirements']}: {t['of_which_must'].format(total=len(functional), must=must)}",
        f"- {t['stories']}: {len(req.get('user_stories') or [])}",
        f"- {t['criteria']}: {len(req.get('acceptance_criteria') or [])}",
        f"- {t['test_result']}: {_qa_sentence(qa, t)}",
        f"- {t['repairs']}: {_repairs(run, t)}",
        f"- {t['run_time']}: " + (t["seconds"].format(n=metrics["run_time_seconds"]) if "run_time_seconds" in metrics else t["not_available"]),
        "",
    ]

    lines += [f"## {t['stages']}", "", f"| {t['stage']} | {t['output']} | {t['result']} |", "|---|---|---|"]
    results = {
        "st_analysis": t["approved"],
        "st_design": t["done"],
        "st_code": t["done"],
        "st_test": _qa_sentence(qa, t),
        "st_docs": t["this_document"],
    }
    for key, outputs in _PLAN_OUTPUTS:
        lines.append(f"| {t[key]} | {' · '.join(outputs)} | {_cell(results[key])} |")
    lines.append("")

    lines += [f"## {t['deliverables']}", ""]
    if files:
        lines += [f"| {t['file']} | {t['size']} |", "|---|---|"]
        lines += [f"| `{name}` | {t['bytes'].format(n=size)} |" for name, size in files.items()]
    else:
        lines.append(t["not_available"])
    lines.append("")

    lines += [f"## {t['scope']}", ""]
    if functional:
        lines += [f"| # | {t['priority']} | {t['requirement']} |", "|---|---|---|"]
        lines += [f"| {r.get('id', '')} | {r.get('priority', '')} | {_cell(r.get('description', ''))} |" for r in functional]
    else:
        lines.append(t["none"])
    lines.append("")

    lines += [f"### {t['out_of_scope']}", ""]
    out_of_scope = req.get("out_of_scope") or []
    if out_of_scope:
        lines += [f"| {t['feature']} | {t['decision']} | {t['reason']} | {t['alternative']} |", "|---|---|---|---|"]
        for item in out_of_scope:
            decision = t.get(item.get("action"), item.get("action") or "")
            lines.append(
                f"| {_cell(item.get('feature', ''))} | {decision} | {_cell(item.get('reason', ''))} | "
                f"{_cell(item.get('alternative') or t['none'])} |"
            )
    else:
        lines.append(t["none"])
    lines.append("")

    lines += [f"### {t['assumptions']}", ""]
    assumptions = req.get("assumptions") or []
    lines += [f"- {a}" for a in assumptions] or [t["none"]]
    lines.append("")

    lines += [f"### {t['decisions']}", ""]
    defaults = [q for q in req.get("clarification_questions") or [] if not q.get("blocking") and q.get("suggested_default")]
    lines += [f"- {q.get('question', '')} → {q['suggested_default']}" for q in defaults] or [t["none"]]
    lines.append("")

    lines += [f"## {t['timeline']}", "", f"| {t['event']} | {t['time']} |", "|---|---|"]
    qa_run = (report or {}).get("run") or {}
    for label, value in (
        ("ev_created", run.get("created_at")),
        ("ev_qa_start", qa_run.get("started_at")),
        ("ev_qa_end", qa_run.get("finished_at")),
        ("ev_docs", _stamp(now)),
    ):
        lines.append(f"| {t[label]} | {value or t['not_available']} |")
    lines.append("")

    lines += [f"## {t['unavailable_title']}", ""]
    lines += [f"- {item}" for item in t["unavailable"]]
    return "\n".join(lines) + "\n"


# ---------- risks.md ----------


def _risks(req, arch, report, run, now, t, qa) -> str:
    app = req["app"]
    rows: List[List[str]] = []

    def add(risk: str, source: str, detail: str) -> None:
        rows.append([risk, source, detail])

    # Testing: defects first, they matter most.
    for check in qa["failed"]:
        message = ((check.get("error") or {}).get("message") or "").strip().splitlines()
        detail = message[0] if message else check.get("description", "")
        screenshot = (check.get("evidence") or {}).get("screenshot")
        if screenshot:
            detail += f" ({t['evidence']}: `{screenshot}`)"
        add(t["r_defect"].format(check=check.get("id", "?")), t["src_qa"], detail)
    if qa["failed"]:
        add(
            t["r_no_repair"],
            t["src_pm"],
            t["r_no_repair_detail"].format(n=len(qa["failed"]), attempts=run.get("repair_attempt") or 0, max=MAX_REPAIR_ATTEMPTS),
        )
    if qa["status"] == "not_run":
        add(t["r_qa_not_run"], t["src_pm"], t["r_qa_not_run_detail"])
    if qa["status"] == "blocked":
        reason = ((report or {}).get("run") or {}).get("blocked_reason") or (run.get("qa") or {}).get("reason") or t["not_available"]
        add(t["r_qa_blocked"], t["src_qa"], str(reason).strip().splitlines()[0])
    for check in qa["skipped"]:
        add(t["r_skipped"].format(check=check.get("id", "?")), t["src_qa"], check.get("skip_reason") or t["not_available"])
    for warning in (report or {}).get("warnings") or []:
        add(t["r_qa_warning"], t["src_qa"], str(warning))
    criteria = len(req.get("acceptance_criteria") or [])
    if qa["summary"] is not None and criteria:
        add(t["r_coverage"], t["src_qa"], t["r_coverage_detail"].format(criteria=criteria))

    # Design limits.
    storage = (arch.get("entity") or {}).get("storage") or {}
    if storage.get("engine", "localStorage") == "localStorage":
        add(t["r_storage"], t["src_arch"], t["r_storage_detail"].format(key=storage.get("key") or t["not_available"]))
    for rule in arch.get("deferred_rules") or []:
        add(t["r_deferred"].format(id=rule.get("requirement_id", "?")), t["src_arch"], rule.get("description", ""))
    for warning in arch.get("warnings") or []:
        add(t["r_arch_warning"], t["src_arch"], str(warning))

    # Scope decisions.
    for item in req.get("out_of_scope") or []:
        detail = item.get("reason", "")
        if item.get("alternative"):
            detail += f" {t['alternative']}: {item['alternative']}"
        add(t["r_out_of_scope"].format(feature=item.get("feature", "?")), t["src_ba"], detail.strip())
    for question in req.get("clarification_questions") or []:
        if not question.get("blocking") and question.get("suggested_default"):
            add(t["r_default"].format(question=question.get("question", "")), t["src_ba"], question["suggested_default"])
    for assumption in req.get("assumptions") or []:
        add(t["r_assumption"], t["src_ba"], str(assumption))

    lines = [f"# {t['risks_title'].format(name=app['name'])}", "", f"> {t['generated'].format(when=_stamp(now))}", ""]
    lines += [f"## {t['open_defects']}", ""]
    if qa["summary"] is None:
        lines.append(t["defects_unknown"])
    elif qa["failed"]:
        lines += [f"- `{c.get('id', '?')}`" for c in qa["failed"]]
    elif qa["status"] == "blocked":
        lines.append(t["defects_unknown"])
    else:
        lines.append(t["no_open_defects"].format(passed=qa["summary"].get("passed"), total=qa["summary"].get("total")))
    lines += ["", f"| # | {t['risk']} | {t['source']} | {t['detail']} |", "|---|---|---|---|"]
    for number, (risk, source, detail) in enumerate(rows, start=1):
        lines.append(f"| R-{number} | {_cell(risk)} | {source} | {_cell(detail)} |")
    return "\n".join(lines) + "\n"


# ---------- helpers ----------


def _qa_sentence(qa: Dict[str, Any], t: Dict[str, Any]) -> str:
    summary = qa["summary"]
    if qa["status"] == "not_run":
        return t["qa_not_run"]
    if qa["status"] == "blocked":
        return t["qa_blocked"]
    if summary is None:
        return t["qa_unknown"]
    numbers = {
        "passed": summary.get("passed"),
        "total": summary.get("total"),
        "failed": summary.get("failed"),
        "skipped": summary.get("skipped"),
    }
    if qa["status"] == "failed":
        return t["qa_failed"].format(**numbers)
    if summary.get("skipped"):
        return t["qa_passed_skipped"].format(**numbers)
    return t["qa_passed"].format(**numbers)


def _repairs(run: Dict[str, Any], t: Dict[str, Any]) -> str:
    attempts = run.get("repair_attempt") or 0
    key = "repairs_value" if attempts else "repairs_none"
    return t[key].format(n=attempts, max=MAX_REPAIR_ATTEMPTS)


def _cell(text: Any) -> str:
    """Make any text safe inside one Markdown table cell."""
    return " ".join(str(text).replace("|", "\\|").split())


def _stamp(moment: datetime) -> str:
    return moment.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
