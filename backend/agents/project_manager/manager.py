"""Project Manager Agent: writes project_plan.md and risks.md for one run.

Everything in the two documents is taken from the inputs:

- ``requirements``  the approved requirements.json (Business Analyst)
- ``architecture``  architecture.json (Software Architect)
- ``qa_report``     test_report.json (QA Tester), or None when QA did not run
- ``run``           the project state: metrics, qa summary, repair_attempt, created_at
- ``files``         generated file name -> size in bytes

Nothing is estimated or invented. BUNYAN does not record a schedule, a cost or
a team for a generated app, so the plan says those are not available instead
of filling them in. The layout follows the draft in
frontend/src/mocks/placeholders.js (mockProjectPlan, mockRisks).
"""

