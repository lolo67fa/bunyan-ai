// Playwright reporter that writes test_report.json (format 0.1.0-proposal).
// Every number in the report comes from the real run: nothing is assumed.
// A check that did not run is reported as "not_run", never as passed.

const fs = require('fs');
const path = require('path');
const { CHECKS } = require('./checks');
const req = require('./requirements');

const SCHEMA_VERSION = '0.1.0-proposal';
const MAX_REPAIR_ATTEMPTS = 2;

const stripAnsi = (s) => String(s || '').replace(/\u001b\[[0-9;]*m/g, '');

class TestReportReporter {
  constructor(options = {}) {
    this.outputFile = path.resolve(req.E2E_DIR, process.env.REPORT_PATH || options.outputFile || 'reports/test_report.json');
    this.results = new Map();
  }

  onBegin(config) {
    this.startedAt = new Date();
    this.playwrightVersion = config.version;
  }

  onTestEnd(test, result) {
    const id = test.title;
    const skip = [...test.annotations, ...(result.annotations || [])].find((a) => a.type === 'skip');
    const evidence = { screenshot: null, trace: null };
    for (const a of result.attachments) {
      if (a.path && a.name === 'screenshot') evidence.screenshot = req.rel(a.path);
      if (a.path && a.name === 'trace') evidence.trace = req.rel(a.path);
    }
    const error = result.errors.length
      ? stripAnsi(result.errors.map((e) => e.message).join('\n')).slice(0, 1500)
      : null;
    this.results.set(id, {
      status: result.status === 'timedOut' || result.status === 'interrupted' ? 'failed' : result.status,
      duration_ms: result.duration,
      error,
      skip_reason: result.status === 'skipped' ? skip?.description || null : null,
      evidence,
    });
  }

  onEnd(fullResult) {
    const finishedAt = new Date();
    const warnings = [];
    let doc = null;
    let entity = null;
    let blockedReason = null;
    try {
      ({ doc, entity } = req.loadRequirements());
    } catch (e) {
      // The input cannot be tested (e.g. two entities, decision D9). This is not an
      // app defect, so no check is reported as failed and nothing goes to the Developer.
      blockedReason = String(e.message);
    }

    if (entity) {
      const forced = entity.fields.filter((f) => f.required && f.type === 'enum' && f.default != null).map((f) => f.name);
      if (forced.length) {
        warnings.push(`Required enum fields with a default cannot be left empty, so empty-input checks skip them: ${forced.join(', ')}`);
      }
    }
    if (req.isHarnessFixture()) {
      warnings.push('App under test is a QA harness fixture, not an app generated by the Developer agent. These results do not prove the team app works.');
    }

    const criteria = doc?.acceptance_criteria || [];
    const checks = CHECKS.map((c) => {
      let r = blockedReason ? null : this.results.get(c.id);
      // Skipped without a reason = never executed (e.g. an earlier hook failed).
      if (r && r.status === 'skipped' && !r.skip_reason) r = null;
      return {
        id: c.id,
        description: c.description,
        status: r ? r.status : 'not_run',
        duration_ms: r ? r.duration_ms : 0,
        related_criteria: criteria.filter((a) => c.criteria_categories.includes(a.category)).map((a) => a.id),
        error: r && r.status === 'failed' ? { message: r.error } : null,
        skip_reason: r ? r.skip_reason : null,
        evidence: r ? r.evidence : { screenshot: null, trace: null },
      };
    });

    const count = (s) => checks.filter((c) => c.status === s).length;
    const total = checks.length;
    const passed = count('passed');
    const attempt = Number(process.env.QA_ATTEMPT || 0);

    const report = {
      schema_version: SCHEMA_VERSION,
      _note: 'PROPOSAL — not an agreed contract yet (owner: Sara)',
      generated_at: finishedAt.toISOString(),
      app: doc ? { name: doc.app?.name, language: doc.language } : null,
      entity: entity ? entity.name : null,
      inputs: {
        requirements_path: req.rel(req.requirementsPath()),
        requirements_schema_version: doc?.schema_version ?? null,
        app_dir: req.rel(req.appDir()),
        is_harness_fixture: req.isHarnessFixture(),
      },
      run: {
        attempt,
        max_repair_attempts: MAX_REPAIR_ATTEMPTS,
        started_at: this.startedAt.toISOString(),
        finished_at: finishedAt.toISOString(),
        duration_ms: finishedAt - this.startedAt,
        browser: 'chromium',
        playwright_version: this.playwrightVersion,
        runner_status: fullResult.status,
        blocked_reason: blockedReason,
      },
      summary: {
        total,
        passed,
        failed: count('failed'),
        skipped: count('skipped'),
        not_run: count('not_run'),
        pass_rate: Math.round((passed / total) * 10000) / 10000,
        all_passed: passed === total,
      },
      checks,
      defects: checks
        .filter((c) => c.status === 'failed')
        .map((c) => ({ check_id: c.id, message: c.error.message, evidence: c.evidence })),
      warnings,
    };

    fs.mkdirSync(path.dirname(this.outputFile), { recursive: true });
    fs.writeFileSync(this.outputFile, JSON.stringify(report, null, 2) + '\n');
    console.log(
      `\ntest_report.json: ${passed}/${total} passed, ${report.summary.failed} failed, ` +
        `${report.summary.skipped} skipped, ${report.summary.not_run} not run — ${report.run.duration_ms} ms\n` +
        `→ ${this.outputFile}`,
    );
  }
}

module.exports = TestReportReporter;
