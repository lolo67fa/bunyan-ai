def test_only_one_qa_run_at_a_time(tmp_path):
    """Sara's runner uses one report file and one port, so runs must not overlap."""
    state = {"inside": 0, "max": 0, "order": []}
    guard = threading.Lock()

    def slow_runner(app_dir, requirements_path, attempt=0, app_path="/"):
        with guard:
            state["inside"] += 1
            state["max"] = max(state["max"], state["inside"])
            state["order"].append(Path(app_dir).parent.name)
        time.sleep(0.15)
        with guard:
            state["inside"] -= 1
        return report_in_saras_format()

    results = {}

    def work(name):
        results[name] = run_pipeline(
            make_project(load_requirements("task_manager_en")), tmp_path / name, lambda p: None, qa_runner=slow_runner,
        )

    threads = [threading.Thread(target=work, args=(f"p{i}",)) for i in range(4)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()

    assert state["max"] == 1
    assert sorted(state["order"]) == ["p0", "p1", "p2", "p3"]  # each project tested exactly once
    assert all(results[name]["qa"]["status"] == "passed" for name in results)
    assert all(files_in(tmp_path / name) == SIX_FILES for name in results)


