@needs_playwright
def test_real_qa_for_two_projects_at_once(tmp_path, real_qa):
    """Both runs finish with their own report although the suite shares one port and one report file."""
    plans = {"task": "task_manager_en", "inventory": "scenario_b_inventory_ar"}
    results = {}

    def work(name):
        results[name] = run_pipeline(make_project(load_requirements(plans[name])), tmp_path / name, lambda p: None)

    threads = [threading.Thread(target=work, args=(name,)) for name in plans]
    for t in threads:
        t.start()
    for t in threads:
        t.join()

    for name in plans:
        assert results[name]["status"] == "completed", results[name]["error"]
        assert results[name]["metrics"]["checks_passed"] == 8
    assert stored_report(tmp_path / "task")["entity"] == "Task"
    assert stored_report(tmp_path / "inventory")["entity"] == "Product"
