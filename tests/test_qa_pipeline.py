class Recorder:
    def __init__(self):
        self.saved = []

    def __call__(self, project):
        self.saved.append(copy.deepcopy(project))

    @property
    def steps(self):
        return [(p["status"], p["current_agent"]) for p in self.saved]


def files_in(folder):
    return sorted(p.relative_to(folder).as_posix() for p in Path(folder).rglob("*") if p.is_file())


def report_in_saras_format(statuses=None, blocked_reason=None, warnings=(), evidence=None, entity="Task"):
    """A report shaped like tests/e2e/lib/report.js writes it. ``statuses`` maps check id -> status."""
    statuses = statuses or {}
    evidence = evidence or {}
    checks = []
    for check_id in CHECK_IDS:
        status = statuses.get(check_id, "passed")
        checks.append({
            "id": check_id,
            "description": f"{check_id} description",
            "status": status,
            "duration_ms": 200 if status in ("passed", "failed") else 0,
            "related_criteria": ["AC-1"],
            "error": {"message": f"{check_id} went wrong"} if status == "failed" else None,
            "skip_reason": "No required field can be left empty" if status == "skipped" else None,
            "evidence": dict(evidence.get(check_id, {"screenshot": None, "trace": None})),
        })
    count = lambda s: sum(1 for c in checks if c["status"] == s)
    return {
        "schema_version": "0.1.0-proposal",
        "generated_at": "2026-11-11T10:00:02.000Z",
        "app": {"name": "Task Manager", "language": "en"},
        "entity": entity,
        "inputs": {
            "requirements_path": "../../../srv/secret/location/requirements.json",
            "requirements_schema_version": "0.1.0-proposal",
            "app_dir": "../../../srv/secret/location/app",
            "is_harness_fixture": False,
        },
        "run": {
            "attempt": 0,
            "max_repair_attempts": 2,
            "started_at": "2026-11-11T10:00:00.000Z",
            "finished_at": "2026-11-11T10:00:02.000Z",
            "duration_ms": 2000,
            "browser": "chromium",
            "playwright_version": "1.64.1",
            "runner_status": "failed" if count("failed") else "passed",
            "blocked_reason": blocked_reason,
        },
        "summary": {
            "total": 8,
            "passed": count("passed"),
            "failed": count("failed"),
            "skipped": count("skipped"),
            "not_run": count("not_run"),
            "pass_rate": round(count("passed") / 8, 4),
            "all_passed": count("passed") == 8,
        },
        "checks": checks,
        "defects": [
            {"check_id": c["id"], "message": c["error"]["message"], "evidence": dict(c["evidence"])}
            for c in checks if c["status"] == "failed"
        ],
        "warnings": list(warnings),
    }


class StandInRunner:
    """Returns a prepared report and records how it was called."""

    def __init__(self, report=None, error=None):
        self.report = report if report is not None else report_in_saras_format()
        self.error = error
        self.calls = []

    def __call__(self, app_dir, requirements_path, attempt=0, app_path="/"):
        self.calls.append({"app_dir": Path(app_dir), "requirements_path": Path(requirements_path), "attempt": attempt})
        if self.error is not None:
            raise self.error
        return copy.deepcopy(self.report)


def run(tmp_path, runner, requirements="task_manager_en"):
    recorder = Recorder()
    project = run_pipeline(make_project(load_requirements(requirements)), tmp_path, recorder, qa_runner=runner)
    return project, recorder


